BEGIN;

CREATE TABLE IF NOT EXISTS findimo.tt_mensaje_alquiler (
    idmensaje bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    idsolicitudalquiler bigint NOT NULL REFERENCES findimo.tt_solicitud_alquiler (idsolicitudalquiler),
    idremitente bigint NOT NULL REFERENCES findimo.tm_usuario (idusuario),
    texto varchar(1000) NOT NULL,
    fecha timestamptz NOT NULL
);

CREATE INDEX IF NOT EXISTS ix_mensaje_alquiler_solicitud
    ON findimo.tt_mensaje_alquiler (idsolicitudalquiler, idmensaje DESC);

COMMIT;

BEGIN;

CREATE TABLE IF NOT EXISTS findimo.tm_tipo_propiedad (
    idtipopropiedad integer GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre varchar(120) NOT NULL UNIQUE,
    estado boolean NOT NULL DEFAULT TRUE
);

ALTER TABLE findimo.tm_propiedad
    ADD COLUMN IF NOT EXISTS idtipopropiedad integer
    REFERENCES findimo.tm_tipo_propiedad (idtipopropiedad);

INSERT INTO findimo.tm_tipo_propiedad (nombre)
VALUES ('Cuarto'), ('Cuarto amoblado'),
       ('Minidepartamento'), ('Minidepartamento compartido'),
       ('Departamento'), ('Departamento compartido'), ('Casa'),
       ('Casa compartida'), ('Residencia estudiantil')
ON CONFLICT (nombre) DO NOTHING;

INSERT INTO findimo.tm_servicio (nombreservicio, estado)
SELECT servicio.nombre, TRUE
FROM (VALUES ('WiFi'), ('Cocina'), ('Lavadora'), ('Secadora'),
    ('Aire acondicionado'),
    ('Agua caliente'), ('Luz incluida'), ('Cámaras de seguridad'),
    ('Refrigeradora'), ('Microondas'),
    ('Limpieza de áreas comunes'), ('Baño compartido')
) AS servicio(nombre)
WHERE NOT EXISTS (
    SELECT 1 FROM findimo.tm_servicio existente
    WHERE lower(trim(existente.nombreservicio)) = lower(servicio.nombre)
);

UPDATE findimo.tm_tipo_propiedad
SET estado = FALSE
WHERE estado = TRUE
  AND lower(trim(nombre)) IN ('estudio', 'estudio amoblado');

UPDATE findimo.tm_servicio
SET estado = FALSE
WHERE estado = TRUE
  AND lower(translate(trim(nombreservicio), 'ÁÉÍÓÚáéíóú', 'AEIOUaeiou')) IN (
    'cama y colchon', 'closet', 'electricidad',
    'escritorio de estudio', 'estacionamiento para bicicletas', 'estacionamiento de bicicletas',
    'seguridad', 'ventilador', 'zona de estudio', 'areas comunes',
    'agua', 'agua incluida', 'calefaccion'
  );

COMMIT;
